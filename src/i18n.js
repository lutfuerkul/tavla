const LANG_KEY = "tavla.lang";

// Whatever was chosen last, else whatever the browser is set to, else Turkish,
// which is the language the game was written in.
function settle() {
  const stored = localStorage.getItem(LANG_KEY);
  if (TEXT[stored]) return stored;
  const asked = (navigator.language || "").slice(0, 2).toLowerCase();
  return TEXT[asked] ? asked : "tr";
}

let lang = settle();
export const language = () => lang;

export function setLanguage(code) {
  if (!TEXT[code]) return;
  lang = code;
  localStorage.setItem(LANG_KEY, code);
}

// A missing key falls back to Turkish rather than to nothing, so a line that
// has not been translated yet is still a line.
export function t(key, vars) {
  const line = TEXT[lang][key] ?? TEXT.tr[key] ?? key;
  if (!vars) return line;
  return line.replace(/\{(\w+)\}/g, (whole, name) =>
    (name in vars ? String(vars[name]) : whole));
}

// Chinese and Japanese have no case to change and no room for letter-spacing;
// the label styles that space Latin capitals out have to leave them alone.
export const isIdeographic = () => lang === "zh" || lang === "ja";
